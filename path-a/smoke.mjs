const uc = new Module.Unicorn(Module.ARCH_ARM, Module.MODE_THUMB | Module.MODE_LITTLE_ENDIAN);
uc.mem_map(0n, 0x10000n, Module.PROT_ALL);
uc.mem_write(0n, [0x00,0x00,0x00,0xea, 0x00,0xf0,0x20,0xe3, 0x00,0xf0,0x20,0xe3, 0xfc,0xff,0xff,0xea]);
const t0 = process.hrtime.bigint();
